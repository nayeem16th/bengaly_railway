export const routeById = (id) => ROUTES.find((r) => r.id === id) || ROUTES[0];
export function routeStops(id, reverse = false) {
  const ids = [...routeById(id).ids];
  if (reverse) ids.reverse();
  return ids.map((key, i) => {
    const [name, bn, lat, lon] = STATIONS[key];
    return { key, name, bn, lat, lon, z: i * 420 };
  });
}
